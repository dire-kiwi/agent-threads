// Generates src/generated.ts from spec/protocol.schema.json (run `make gen` at the repo root,
// which bundles the schemas first).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const bundle = JSON.parse(readFileSync(join(here, "../../../../spec/protocol.schema.json"), "utf8"));

// json-schema-to-typescript makes a new type for a $ref with siblings (e.g. a description), and an
// object type for a schema with no type at all; we want the referenced type, and unknown.
function prepare(node) {
  if (Array.isArray(node)) return node.map(prepare);
  if (node === null || typeof node !== "object") return node;
  if (node.$ref) return { $ref: node.$ref };
  const out = Object.fromEntries(Object.entries(node).map(([k, v]) => [k, k === "properties" || k === "$defs" ? prepareAll(v) : prepare(v)]));
  return out;
}
function prepareAll(schemas) {
  return Object.fromEntries(
    Object.entries(schemas).map(([k, v]) => {
      const typed = ["type", "$ref", "oneOf", "anyOf", "allOf", "const", "enum"].some((key) => key in v);
      return [k, prepare(typed ? v : { ...v, tsType: "unknown" })];
    }),
  );
}

// The bundle's root is only a container for $defs.
const schema = { title: "Protocol", $defs: prepareAll(bundle.$defs) };
let ts = await compile(schema, "Protocol", {
  bannerComment:
    "// Generated by ts/packages/protocol/scripts/gen.mjs from spec/protocol.schema.json. Don't edit;\n// change spec/schema/ and run `make gen`.",
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  format: true,
  style: { printWidth: 120 },
});
ts = ts
  .replace(/export interface Protocol \{[^}]*\}\n/, "")
  .replace(/ \*\n \* This interface was referenced by `Protocol`'s JSON-Schema\n \* via the `definition` "\w+".\n/g, "")
  .replace(/\/\*\*\n \* This interface was referenced by `Protocol`'s JSON-Schema\n \* via the `definition` "\w+".\n \*\/\n/g, "");
writeFileSync(join(here, "../src/generated.ts"), ts);

// The bundle itself, for validating values at run time (src/validate.ts). Descriptions and examples
// are left out: they're for people, and the types have them.
function strip(node) {
  if (Array.isArray(node)) return node.map(strip);
  if (node === null || typeof node !== "object") return node;
  return Object.fromEntries(
    Object.entries(node)
      .filter(([k]) => !["description", "examples", "title", "$comment"].includes(k))
      .map(([k, v]) => [k, k === "properties" || k === "$defs" ? Object.fromEntries(Object.entries(v).map(([n, d]) => [n, strip(d)])) : strip(v)]),
  );
}
writeFileSync(
  join(here, "../src/schema.ts"),
  "// Generated by ts/packages/protocol/scripts/gen.mjs from spec/protocol.schema.json. Don't edit;\n// change spec/schema/ and run `make gen`.\n\n" +
    "/** The protocol's JSON Schema definitions, by name. */\n" +
    `export const schema: { readonly $defs: { readonly [name: string]: unknown } } = ${JSON.stringify({ $defs: strip(bundle.$defs) }, null, 2)};\n`,
);
