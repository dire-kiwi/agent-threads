// Generates src/codex/protocol.ts, the types of the Codex app-server messages the Codex driver
// sends and reads, from the schema the installed codex prints:
//
//   pnpm --filter @dire-kiwi/agent-threads-node gen:codex      # CODEX_BIN names another codex
//
// `codex app-server generate-json-schema --experimental` describes the whole protocol (800-odd
// types); only the ones reachable from ROOTS are kept. Re-run it when Codex changes, and check the
// driver against the diff.

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const bin = process.env.CODEX_BIN ?? "codex";

/** The messages the driver uses: what it sends, what it answers, and what it reads. */
const ROOTS = [
  // Requests it sends, and their responses.
  "InitializeParams",
  "InitializeResponse",
  "ThreadStartParams",
  "ThreadStartResponse",
  "ThreadResumeParams",
  "ThreadResumeResponse",
  "TurnStartParams",
  "TurnStartResponse",
  "TurnSteerParams",
  "TurnSteerResponse",
  "TurnInterruptParams",
  "ThreadCompactStartParams",
  "SkillsExtraRootsSetParams",
  "SkillsListParams",
  "SkillsListResponse",
  "DynamicToolSpec",
  // The server's requests, and the driver's answers.
  "CommandExecutionRequestApprovalParams",
  "CommandExecutionRequestApprovalResponse",
  "FileChangeRequestApprovalParams",
  "FileChangeRequestApprovalResponse",
  "PermissionsRequestApprovalParams",
  "PermissionsRequestApprovalResponse",
  "McpServerElicitationRequestParams",
  "McpServerElicitationRequestResponse",
  "ToolRequestUserInputParams",
  "ToolRequestUserInputResponse",
  "DynamicToolCallParams",
  "DynamicToolCallResponse",
  // Notifications.
  "ThreadItem",
  "ItemStartedNotification",
  "ItemCompletedNotification",
  "AgentMessageDeltaNotification",
  "ReasoningSummaryTextDeltaNotification",
  "ReasoningTextDeltaNotification",
  "TurnStartedNotification",
  "TurnCompletedNotification",
  "TurnPlanUpdatedNotification",
  "ThreadTokenUsageUpdatedNotification",
  "ThreadStartedNotification",
  "ErrorNotification",
  "WarningNotification",
];

const out = mkdtempSync(join(tmpdir(), "codex-schema-"));
let version;
let bundle;
try {
  version = execFileSync(bin, ["--version"], { encoding: "utf8" }).trim();
  execFileSync(bin, ["app-server", "generate-json-schema", "--experimental", "--out", out], { stdio: ["ignore", "ignore", "inherit"] });
  bundle = JSON.parse(readFileSync(join(out, "codex_app_server_protocol.schemas.json"), "utf8"));
} finally {
  rmSync(out, { recursive: true, force: true });
}

// The bundle keeps the v2 protocol's types under definitions.v2; they're put alongside the rest.
const { v2 = {}, ...top } = bundle.definitions;
const defs = { ...v2, ...top };
const fixRefs = (node) => {
  if (Array.isArray(node)) return node.map(fixRefs);
  if (node === null || typeof node !== "object") return node;
  const o = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "$schema") continue;
    o[k] = k === "$ref" && typeof v === "string" ? v.replace("#/definitions/v2/", "#/definitions/") : fixRefs(v);
  }
  return o;
};

// What the roots reach.
const keep = new Set();
const visit = (name) => {
  if (keep.has(name)) return;
  if (!defs[name]) throw new Error(`the schema has no ${name}`);
  keep.add(name);
  JSON.stringify(defs[name], (k, v) => {
    if (k === "$ref" && typeof v === "string") visit(v.replace(/^#\/definitions\/(v2\/)?/, ""));
    return v;
  });
};
ROOTS.forEach(visit);

// json-schema-to-typescript names a type by its title when it has one, which some of Codex's
// share; the definition's own name is unique.
const definitions = {};
for (const name of [...keep].sort()) {
  const { title: _t, ...d } = fixRefs(defs[name]);
  definitions[name] = d;
}

let ts = await compile({ title: "CodexProtocol", definitions }, "CodexProtocol", {
  bannerComment: `// Generated by ts/packages/node/scripts/gen-codex.mjs from the schema of ${version}'s app server\n// (codex app-server generate-json-schema --experimental). Don't edit; run \`pnpm gen:codex\`.`,
  additionalProperties: true,
  unreachableDefinitions: true,
  declareExternallyReferenced: true,
  format: true,
  style: { printWidth: 120 },
});
// The root is only a container for the definitions.
ts = ts
  .replace(/export interface CodexProtocol \{[^}]*\}\n/, "")
  .replace(/ \*\n \* This interface was referenced by `CodexProtocol`'s JSON-Schema\n \* via the `definition` "\w+".\n/g, "")
  .replace(/\/\*\*\n \* This interface was referenced by `CodexProtocol`'s JSON-Schema\n \* via the `definition` "\w+".\n \*\/\n/g, "");
writeFileSync(join(here, "../src/codex/protocol.ts"), ts);
console.log(`src/codex/protocol.ts: ${keep.size} types from ${version}`);
