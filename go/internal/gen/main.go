// Command gen generates protocol/protocol_gen.go from spec/protocol.schema.json. Run `make gen` at
// the repo root, which bundles the schemas first.
//
// It understands the subset of JSON Schema the spec uses: $defs that are objects, string enums or
// unions (a oneOf of $refs to objects told apart by a "type" constant), and properties that are
// strings, integers, numbers, booleans, arrays, maps (additionalProperties), $refs, string enums
// or anything ({}). Anything else is an error, so the spec stays within what every language's
// generator handles.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"slices"
	"strings"
)

func main() {
	in := flag.String("in", "../spec/protocol.schema.json", "the bundled schema")
	out := flag.String("out", "protocol/protocol_gen.go", "the Go file to write")
	flag.Parse()
	log.SetFlags(0)
	log.SetPrefix("gen: ")

	data, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	root, err := parse(data)
	if err != nil {
		log.Fatalf("%s: %v", *in, err)
	}
	defs, ok := root.get("$defs").(*object)
	if !ok {
		log.Fatalf("%s: no $defs", *in)
	}
	g := &generator{defs: defs, tags: map[string]string{}, unionOf: map[string]string{}}
	src := g.file()
	formatted, err := format.Source(src)
	if err != nil {
		os.WriteFile(*out, src, 0o644)
		log.Fatalf("formatting %s: %v", *out, err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

// object is a JSON object that keeps its keys' order, so the Go fields follow the schema's.
type object struct {
	keys []string
	vals map[string]any
}

func (o *object) get(k string) any {
	if o == nil {
		return nil
	}
	return o.vals[k]
}

func (o *object) str(k string) string {
	s, _ := o.get(k).(string)
	return s
}

func (o *object) has(k string) bool {
	_, ok := o.vals[k]
	return o != nil && ok
}

func parse(data []byte) (*object, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.UseNumber()
	v, err := value(dec)
	if err != nil {
		return nil, err
	}
	o, ok := v.(*object)
	if !ok {
		return nil, fmt.Errorf("not an object")
	}
	return o, nil
}

func value(dec *json.Decoder) (any, error) {
	tok, err := dec.Token()
	if err != nil {
		return nil, err
	}
	switch tok {
	case json.Delim('{'):
		o := &object{vals: map[string]any{}}
		for dec.More() {
			k, err := dec.Token()
			if err != nil {
				return nil, err
			}
			v, err := value(dec)
			if err != nil {
				return nil, err
			}
			o.keys = append(o.keys, k.(string))
			o.vals[k.(string)] = v
		}
		_, err = dec.Token()
		return o, err
	case json.Delim('['):
		var list []any
		for dec.More() {
			v, err := value(dec)
			if err != nil {
				return nil, err
			}
			list = append(list, v)
		}
		_, err = dec.Token()
		return list, err
	}
	return tok, nil
}

type generator struct {
	defs *object
	buf  bytes.Buffer
	// tags: variant name → its "type" constant. unionOf: variant name → its union.
	tags    map[string]string
	unionOf map[string]string
	// The enums made for properties, written after the struct that has them.
	inline []string
}

func (g *generator) p(format string, args ...any) {
	fmt.Fprintf(&g.buf, format, args...)
}

func (g *generator) file() []byte {
	for _, name := range g.defs.keys {
		def := g.defs.get(name).(*object)
		variants, ok := def.get("oneOf").([]any)
		if !ok {
			continue
		}
		for _, v := range variants {
			ref := refName(v.(*object).str("$ref"))
			vdef, _ := g.defs.get(ref).(*object)
			typ, _ := vdef.get("properties").(*object).get("type").(*object)
			tag := typ.str("const")
			if ref == "" || tag == "" {
				log.Fatalf("$defs/%s: each oneOf variant must be a $ref to an object with a type constant", name)
			}
			g.tags[ref] = tag
			g.unionOf[ref] = name
		}
	}

	g.p("// Code generated by internal/gen from spec/protocol.schema.json. DO NOT EDIT.\n")
	g.p("// Change spec/schema/ and run `make gen`.\n\n")
	g.p("package protocol\n\n")
	g.p("import (\n\"encoding/json\"\n\"fmt\"\n)\n\n")
	for _, name := range g.defs.keys {
		def := g.defs.get(name).(*object)
		switch {
		case def.has("oneOf"):
			g.union(name, def)
		case def.has("enum"):
			g.enum(name, def.str("description"), def.get("enum").([]any))
		case def.str("type") == "object":
			g.object(name, def)
		default:
			log.Fatalf("$defs/%s: unsupported schema (want an object, a string enum or a oneOf)", name)
		}
		for _, s := range g.inline {
			g.buf.WriteString(s)
		}
		g.inline = nil
	}
	return g.buf.Bytes()
}

func (g *generator) union(name string, def *object) {
	var variants []string
	for _, v := range def.get("oneOf").([]any) {
		variants = append(variants, refName(v.(*object).str("$ref")))
	}
	ptrs := make([]string, len(variants))
	for i, v := range variants {
		ptrs[i] = "*" + v
	}
	g.doc(name, def.str("description")+"\n\nValue is one of "+strings.Join(ptrs, ", ")+".")
	g.p("type %s struct {\nValue %sValue\n}\n\n", name, name)
	g.p("// %sValue is implemented by the variants of %s.\n", name, name)
	g.p("type %sValue interface {\n// Type is the variant's \"type\".\nType() string\nis%s()\n}\n\n", name, name)
	for _, v := range variants {
		g.p("func (*%s) Type() string { return %q }\n", v, g.tags[v])
		g.p("func (*%s) is%s() {}\n", v, name)
	}
	g.p("\nfunc (u %s) MarshalJSON() ([]byte, error) {\n", name)
	g.p("if u.Value == nil {\nreturn nil, fmt.Errorf(\"protocol: %s has no Value\")\n}\n", name)
	g.p("return json.Marshal(u.Value)\n}\n\n")
	g.p("func (u *%s) UnmarshalJSON(data []byte) error {\n", name)
	g.p("var t struct {\nType string `json:\"type\"`\n}\n")
	g.p("if err := json.Unmarshal(data, &t); err != nil {\nreturn err\n}\n")
	g.p("var v %sValue\nswitch t.Type {\n", name)
	for _, v := range variants {
		g.p("case %q:\nv = new(%s)\n", g.tags[v], v)
	}
	g.p("default:\nreturn fmt.Errorf(\"protocol: unknown %s type %%q\", t.Type)\n}\n", name)
	g.p("if err := json.Unmarshal(data, v); err != nil {\nreturn err\n}\n")
	g.p("u.Value = v\nreturn nil\n}\n\n")
}

func (g *generator) enum(name, description string, values []any) {
	g.doc(name, description)
	g.p("type %s string\n\nconst (\n", name)
	for _, v := range values {
		s, ok := v.(string)
		if !ok {
			log.Fatalf("%s: only string enums are supported", name)
		}
		g.p("%s%s %s = %q\n", name, camel(s), name, s)
	}
	g.p(")\n\n")
}

type field struct {
	doc, name, json, typ string
	omitempty       bool
	// A required array or map, which must marshal as [] or {} rather than null.
	nonNil string
}

func (g *generator) object(name string, def *object) {
	props, _ := def.get("properties").(*object)
	required := map[string]bool{}
	if list, ok := def.get("required").([]any); ok {
		for _, r := range list {
			required[r.(string)] = true
		}
	}
	tag, isVariant := g.tags[name]
	var fields []field
	if props != nil {
		for _, key := range props.keys {
			if isVariant && key == "type" {
				continue
			}
			prop := props.get(key).(*object)
			typ, kind := g.typeOf(name, key, prop)
			f := field{name: camel(key), json: key, typ: typ, omitempty: !required[key]}
			if !required[key] && (kind == "number" || kind == "struct") {
				f.typ = "*" + typ
			}
			if required[key] && (kind == "slice" || kind == "map") {
				f.nonNil = typ
			}
			if d := prop.str("description"); d != "" {
				f.doc = comment(d)
			}
			fields = append(fields, f)
		}
	}
	description := def.str("description")
	if isVariant {
		description = strings.TrimSpace(description + fmt.Sprintf("\n\nIt's the %q variant of %s.", tag, g.unionOf[name]))
	}
	g.doc(name, description)
	g.p("type %s struct {\n", name)
	for _, f := range fields {
		opt := ""
		if f.omitempty {
			opt = ",omitempty"
		}
		if f.doc != "" {
			g.p("\n%s", f.doc)
		}
		g.p("%s %s `json:\"%s%s\"`\n", f.name, f.typ, f.json, opt)
	}
	g.p("}\n\n")

	var nonNil []field
	for _, f := range fields {
		if f.nonNil != "" {
			nonNil = append(nonNil, f)
		}
	}
	if !isVariant && len(nonNil) == 0 {
		return
	}
	g.p("func (v %s) MarshalJSON() ([]byte, error) {\ntype plain %s\np := plain(v)\n", name, name)
	for _, f := range nonNil {
		g.p("if p.%s == nil {\np.%s = %s{}\n}\n", f.name, f.name, f.nonNil)
	}
	if isVariant {
		g.p("return json.Marshal(struct {\nType string `json:\"type\"`\nplain\n}{%q, p})\n}\n\n", tag)
	} else {
		g.p("return json.Marshal(p)\n}\n\n")
	}
}

// typeOf is the Go type of a property, and what kind of type it is: string, bool, number,
// struct, slice, map or any.
func (g *generator) typeOf(parent, key string, prop *object) (string, string) {
	if ref := prop.str("$ref"); ref != "" {
		name := refName(ref)
		def, ok := g.defs.get(name).(*object)
		if !ok {
			log.Fatalf("%s.%s: $ref to missing %s", parent, key, ref)
		}
		if def.has("enum") {
			return name, "string"
		}
		return name, "struct"
	}
	if values, ok := prop.get("enum").([]any); ok {
		name := parent + camel(key)
		saved := g.buf
		g.buf = bytes.Buffer{}
		g.enum(name, prop.str("description"), values)
		g.inline = append(g.inline, g.buf.String())
		g.buf = saved
		return name, "string"
	}
	switch prop.str("type") {
	case "string":
		return "string", "string"
	case "boolean":
		return "bool", "bool"
	case "integer":
		return "int64", "number"
	case "number":
		return "float64", "number"
	case "array":
		items, ok := prop.get("items").(*object)
		if !ok {
			log.Fatalf("%s.%s: an array needs items", parent, key)
		}
		typ, _ := g.typeOf(parent, key+"_item", items)
		return "[]" + typ, "slice"
	case "object":
		if prop.has("properties") {
			log.Fatalf("%s.%s: an object property with properties should be a $def", parent, key)
		}
		switch extra := prop.get("additionalProperties").(type) {
		case *object:
			typ, _ := g.typeOf(parent, key+"_value", extra)
			return "map[string]" + typ, "map"
		case bool:
			if extra {
				return "map[string]any", "map"
			}
		}
		log.Fatalf("%s.%s: an object property needs additionalProperties", parent, key)
	case "":
		for _, k := range []string{"oneOf", "anyOf", "allOf", "const"} {
			if prop.has(k) {
				log.Fatalf("%s.%s: unsupported %s", parent, key, k)
			}
		}
		return "json.RawMessage", "any"
	}
	log.Fatalf("%s.%s: unsupported type %q", parent, key, prop.str("type"))
	return "", ""
}

func (g *generator) doc(name, description string) {
	if description == "" {
		return
	}
	text := comment(description)
	first := strings.TrimPrefix(text, "// ")
	// Go doc comments start with the name.
	if !strings.HasPrefix(first, name+" ") {
		text = comment(name + ": " + description)
	}
	g.p("%s", text)
}

// comment wraps text into // lines of at most 100 columns.
func comment(text string) string {
	var b strings.Builder
	for i, para := range strings.Split(strings.TrimSpace(text), "\n\n") {
		if i > 0 {
			b.WriteString("//\n")
		}
		line := "//"
		for _, word := range strings.Fields(para) {
			if len(line)+1+len(word) > 100 && line != "//" {
				b.WriteString(line + "\n")
				line = "//"
			}
			line += " " + word
		}
		b.WriteString(line + "\n")
	}
	return b.String()
}

func refName(ref string) string {
	return strings.TrimPrefix(ref, "#/$defs/")
}

var initialisms = []string{"id", "ok", "url", "usd", "json", "api", "http", "mcp"}

// camel turns snake_case, kebab-case or dotted names into Go's CamelCase.
func camel(s string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == '.' }) {
		if slices.Contains(initialisms, part) {
			b.WriteString(strings.ToUpper(part))
		} else {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}
