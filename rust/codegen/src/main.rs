//! Generates `agent-threads/src/protocol.rs` from `spec/protocol.schema.json` with typify.
//! Run `make gen` at the repo root, which bundles the schemas first.
//!
//! The spec's unions (Item, ThreadEvent, ThreadRequest, Command) are `oneOf`s of objects told apart
//! by a `type` constant. typify would make them untagged enums whose structs keep `type` as a
//! `serde_json::Value`, which matches any variant. So the `type` properties are taken out of the
//! schema before typify sees it, and the enums typify makes are turned into serde internally
//! tagged enums (`#[serde(tag = "type")]`) afterwards, with their variants named without the
//! union's last word (`ThreadEvent::ItemAdded(ItemAddedEvent)`).

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use quote::{format_ident, quote};
use serde_json::{Map, Value};
use typify::{TypeSpace, TypeSpaceSettings};

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let bundle = fs::read_to_string(root.join("spec/protocol.schema.json")).expect("read spec/protocol.schema.json");
    let mut bundle: Value = serde_json::from_str(&bundle).expect("parse the bundle");
    draft7(&mut bundle);
    let Some(Value::Object(mut defs)) = bundle.get_mut("definitions").map(Value::take) else {
        panic!("the bundle has no $defs");
    };
    let unions = untag(&mut defs);

    let mut types = TypeSpace::new(TypeSpaceSettings::default().with_struct_builder(false));
    let defs = defs.into_iter().map(|(name, def)| {
        let schema = serde_json::from_value(def).unwrap_or_else(|e| panic!("$defs/{name}: {e}"));
        (name, schema)
    });
    types.add_ref_types(defs).expect("convert the schema");
    let mut file = syn::parse2::<syn::File>(types.to_stream()).expect("parse the generated code");
    tag(&mut file, &unions);
    skip_false(&mut file);
    optional_lists(&mut file);
    let code = format!(
        "// Generated by rust/codegen from spec/protocol.schema.json. Don't edit;\n\
         // change spec/schema/ and run `make gen`.\n\
         #![allow(clippy::all, missing_docs)]\n\n{}",
        prettyplease::unparse(&file)
    );
    fs::write(root.join("rust/agent-threads/src/protocol.rs"), code).expect("write protocol.rs");
}

/// typify reads draft-07 schemas, which keep definitions under `definitions`. Timestamps stay
/// strings, as they are in the other languages, so they go through unchanged.
fn draft7(node: &mut Value) {
    match node {
        Value::Object(map) => {
            if let Some(defs) = map.remove("$defs") {
                map.insert("definitions".into(), defs);
            }
            if let Some(Value::String(r)) = map.get_mut("$ref") {
                *r = r.replace("#/$defs/", "#/definitions/");
            }
            if map.get("format").and_then(Value::as_str) == Some("date-time") {
                map.remove("format");
            }
            map.values_mut().for_each(draft7);
        }
        Value::Array(list) => list.iter_mut().for_each(draft7),
        _ => {}
    }
}

/// Takes the `type` constant out of each union's variants, and returns each union's variants:
/// union name → [(variant type name, tag)].
fn untag(defs: &mut Map<String, Value>) -> BTreeMap<String, Vec<(String, String)>> {
    let mut unions = BTreeMap::new();
    for (name, def) in defs.iter() {
        let Some(Value::Array(variants)) = def.get("oneOf") else {
            continue;
        };
        let variants = variants.iter().map(|v| {
            let r = v["$ref"]
                .as_str()
                .unwrap_or_else(|| panic!("$defs/{name}: a oneOf variant isn't a $ref"));
            r.trim_start_matches("#/definitions/").to_string()
        });
        unions.insert(name.clone(), variants.map(|v| (v, String::new())).collect::<Vec<_>>());
    }
    for (name, variants) in unions.iter_mut() {
        for (variant, tag) in variants.iter_mut() {
            let def = defs[variant.as_str()].as_object_mut().unwrap();
            let props = def["properties"].as_object_mut().unwrap();
            let constant = props.remove("type").and_then(|t| t.get("const").cloned());
            *tag = constant
                .and_then(|c| c.as_str().map(String::from))
                .unwrap_or_else(|| panic!("$defs/{variant} (in {name}): no type constant"));
            if let Some(Value::Array(required)) = def.get_mut("required") {
                required.retain(|r| r != "type");
            }
        }
    }
    unions
}

/// Makes each union's enum internally tagged by `type`, and names its variants without the
/// union's last word (`ThreadEvent::ItemAdded` holds an `ItemAddedEvent`, `Command::Interrupt` an
/// `InterruptCommand`); the structs keep their names.
fn tag(file: &mut syn::File, unions: &BTreeMap<String, Vec<(String, String)>>) {
    let mut renamed = BTreeMap::new(); // (union, variant type) -> variant name
    for item in &mut file.items {
        let syn::Item::Enum(e) = item else { continue };
        let union = e.ident.to_string();
        let Some(variants) = unions.get(&union) else {
            continue;
        };
        let untagged = e
            .attrs
            .iter()
            .position(|a| a.path().is_ident("serde") && quote!(#a).to_string().contains("untagged"));
        e.attrs[untagged.unwrap_or_else(|| panic!("{} isn't untagged", e.ident))] =
            syn::parse_quote!(#[serde(tag = "type")]);
        let suffix = &union[union.rfind(char::is_uppercase).unwrap()..];
        for v in &mut e.variants {
            let syn::Fields::Unnamed(fields) = &v.fields else {
                panic!("{}::{} isn't a newtype variant", e.ident, v.ident)
            };
            let ty = &fields.unnamed[0].ty;
            let ty = quote!(#ty).to_string();
            let (_, tag) = variants
                .iter()
                .find(|(name, _)| *name == ty)
                .unwrap_or_else(|| panic!("{}::{}: unknown type {ty}", e.ident, v.ident));
            v.attrs.push(syn::parse_quote!(#[serde(rename = #tag)]));
            if let Some(short) = ty.strip_suffix(suffix).filter(|s| !s.is_empty()) {
                v.ident = format_ident!("{short}");
            }
            renamed.insert((union.clone(), ty), v.ident.clone());
        }
    }
    // The From impls typify makes for each variant's type name the variant too.
    for item in &mut file.items {
        let syn::Item::Impl(imp) = item else { continue };
        let Some((_, path, _)) = &imp.trait_ else { continue };
        let last = path.segments.last().unwrap();
        let syn::PathArguments::AngleBracketed(args) = &last.arguments else {
            continue;
        };
        let Some(syn::GenericArgument::Type(ty)) = args.args.first().filter(|_| last.ident == "From") else {
            continue;
        };
        let self_ty = &imp.self_ty;
        if let Some(variant) = renamed.get(&(quote!(#self_ty).to_string(), quote!(#ty).to_string())) {
            imp.items = vec![syn::parse_quote!(fn from(value: #ty) -> Self { Self::#variant(value) })];
        }
    }
}

/// Leaves out booleans that are false, as the other languages do: in the spec an optional boolean
/// defaults to false, so false and absent are the same.
fn skip_false(file: &mut syn::File) {
    for item in &mut file.items {
        let syn::Item::Struct(s) = item else { continue };
        for field in &mut s.fields {
            let ty = &field.ty;
            if quote!(#ty).to_string() != "bool" {
                continue;
            }
            for attr in &mut field.attrs {
                if attr.path().is_ident("serde") && quote!(#attr).to_string() == "# [serde (default)]" {
                    *attr = syn::parse_quote!(#[serde(default, skip_serializing_if = "std::ops::Not::not")]);
                }
            }
        }
    }
}

/// Lists where absent and empty mean different things (absent: leave it as it is; empty: clear
/// it), which typify would make `Vec`s that are empty when absent: they're `Option<Vec>`s.
const OPTIONAL_LISTS: &[(&str, &str)] = &[("SetOptionsCommand", "standing_answers")];

fn optional_lists(file: &mut syn::File) {
    for item in &mut file.items {
        let syn::Item::Struct(s) = item else { continue };
        for field in &mut s.fields {
            let name = (s.ident.to_string(), field.ident.as_ref().map(ToString::to_string));
            if !OPTIONAL_LISTS
                .iter()
                .any(|(t, f)| name.0 == *t && name.1.as_deref() == Some(*f))
            {
                continue;
            }
            let ty = &field.ty;
            field.ty = syn::parse_quote!(::std::option::Option<#ty>);
            for attr in &mut field.attrs {
                if attr.path().is_ident("serde") {
                    *attr = syn::parse_quote!(#[serde(default, skip_serializing_if = "::std::option::Option::is_none")]);
                }
            }
        }
    }
}
